"""Builds jmdm_app/icons/*.ttf: the few Fluent UI System Icons the app uses
(Microsoft, MIT licence), packed into two small fonts, plus the name -> code
point map in jmdm_app/icon_map.py.

    pip install fonttools
    git clone --depth 1 https://github.com/microsoft/fluentui-system-icons
    python tools/make_icon_font.py path/to/fluentui-system-icons/fonts

To add an icon: put its Fluent name in ICONS below and run this again."""
import json
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# app name -> (Fluent name, style). Sizes 20 (crisp at 14-22 px).
ICONS = {
    "add": ("add", "regular"), "resume": ("play", "filled"), "pause": ("pause", "filled"),
    "stop": ("stop", "filled"), "stop_all": ("record_stop", "filled"),
    "delete": ("delete", "regular"), "video": ("video", "regular"),
    "clock": ("clock", "regular"), "scheduler": ("calendar_clock", "regular"),
    "queue": ("task_list_ltr", "regular"), "more": ("more_horizontal", "regular"),
    "grid": ("grid", "regular"), "down": ("arrow_download", "regular"),
    "check": ("checkmark_circle", "filled"), "check_plain": ("checkmark", "regular"),
    "warn": ("warning", "filled"), "box": ("folder_zip", "regular"),
    "app": ("window_apps", "regular"), "film": ("video_clip", "regular"),
    "music": ("music_note_2", "regular"), "doc": ("document_text", "regular"),
    "file": ("document", "regular"), "moon": ("weather_moon", "regular"),
    "sun": ("weather_sunny", "regular"), "search": ("search", "regular"),
    "folder": ("folder_open", "regular"), "copy": ("copy", "regular"),
    "retry": ("arrow_clockwise", "regular"), "chevron": ("chevron_down", "regular"),
    "chevron_right": ("chevron_right", "regular"), "gear": ("settings", "regular"),
    "hourglass": ("hourglass_half", "regular"), "info": ("info", "filled"),
    "question": ("question_circle", "filled"), "error": ("error_circle", "filled"),
    "link": ("link", "regular"), "dismiss": ("dismiss", "regular"),
    "open": ("open", "regular"), "update": ("arrow_sync", "regular"),
    "exit": ("arrow_exit", "regular"), "mirror": ("arrow_swap", "regular"),
    "move": ("arrow_move", "regular"), "pause_line": ("pause", "regular"),
    "play_line": ("play", "regular"), "broom": ("broom", "regular"),
    "options": ("options", "regular"), "radio_on": ("radio_button", "filled"),
    "dot": ("circle", "filled"),
}
FAMILY = {"regular": "JMDM Icons", "filled": "JMDM Icons Filled"}


def main(src):
    out_map, codes = {}, {"regular": set(), "filled": set()}
    maps = {s: json.load(open(os.path.join(src, f"FluentSystemIcons-{s.title()}.json")))
            for s in ("regular", "filled")}
    for key, (name, style) in ICONS.items():
        glyph = f"ic_fluent_{name}_20_{style}"
        if glyph not in maps[style]:
            sys.exit(f"missing {glyph}")
        cp = maps[style][glyph]
        codes[style].add(cp)
        out_map[key] = (style, cp)
    os.makedirs(os.path.join(HERE, "jmdm_app", "icons"), exist_ok=True)
    for style, cps in codes.items():
        font = TTFont(os.path.join(src, f"FluentSystemIcons-{style.title()}.ttf"))
        opts = subset.Options()
        opts.layout_features = []
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=sorted(cps))
        sub.subset(font)
        fam = FAMILY[style]
        for rec in font["name"].names:                 # own name: never clashes
            if rec.nameID in (1, 4, 16):
                rec.string = fam
            elif rec.nameID == 6:
                rec.string = fam.replace(" ", "")
        font.save(os.path.join(HERE, "jmdm_app", "icons", f"jmdm-icons-{style}.ttf"))
    with open(os.path.join(HERE, "jmdm_app", "icon_map.py"), "w", encoding="utf-8") as fh:
        fh.write('"""Generated by tools/make_icon_font.py — icon name -> (style, code point)\n'
                 'in jmdm_app/icons/jmdm-icons-*.ttf (Fluent UI System Icons, MIT)."""\n')
        fh.write(f"FAMILY = {FAMILY!r}\n")
        fh.write("ICONS = {\n")
        for k, (style, cp) in sorted(out_map.items()):
            fh.write(f"    {k!r}: ({style!r}, 0x{cp:x}),\n")
        fh.write("}\n")
    print("ok:", len(out_map), "icons")


if __name__ == "__main__":
    main(sys.argv[1])
